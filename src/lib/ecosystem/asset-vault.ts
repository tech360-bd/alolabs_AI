function computeHash(value: unknown): string {
  return createHash('sha256').update(JSON.stringify(value)).digest('hex');
}

/**
 * Idempotently syncs all 30 supplied sources, vetted assets, license records,
 * security reviews, and initial pinned Asset Vault integrations into Prisma.
 * Never deletes or overwrites custom operator versions.
 */
export async function syncAssetVaultToDb(createdBy = 'system-intake'): Promise<{
  sourcesUpserted: number;
  assetsUpserted: number;
  integrationsEnsured: number;
}> {
  let sourcesUpserted = 0;
  let assetsUpserted = 0;
  let integrationsEnsured = 0;

  const sourceIdBySlug = new Map<string, string>();
  for (const s of SUPPLIED_SOURCES) {
    const row = await db.externalSource.upsert({
      where: { slug: s.slug },
      update: {
        url: s.url,
        sourceKind: s.sourceKind,
        displayName: s.displayName,
        category: s.category,
        availability: s.availability,
        paginationTotal: s.paginationTotal,
        reposDiscovered: s.reposDiscovered,
        notes: s.notes,
        fetchedAt: new Date(`${INTAKE_FETCHED_AT}T00:00:00.000Z`),
      },
      create: {
        id: randomUUID(),
        slug: s.slug,
        url: s.url,
        sourceKind: s.sourceKind,
        displayName: s.displayName,
        category: s.category,
        availability: s.availability,
        paginationTotal: s.paginationTotal,
        reposDiscovered: s.reposDiscovered,
        notes: s.notes,
        fetchedAt: new Date(`${INTAKE_FETCHED_AT}T00:00:00.000Z`),
      },
    });
    sourceIdBySlug.set(s.slug, row.id);
    sourcesUpserted += 1;
  }

  for (const a of VETTED_ECOSYSTEM_ASSETS) {
    const sourceId = sourceIdBySlug.get(a.sourceSlug);
    if (!sourceId) continue;

    const existing = await db.externalAsset.findUnique({ where: { url: a.url } });
    const assetRow = existing
      ? await db.externalAsset.update({
          where: { id: existing.id },
          data: {
            sourceId,
            fullName: a.fullName,
            kind: a.kind,
            defaultBranch: a.defaultBranch,
            headSha: a.headSha,
            stars: a.stars,
            language: a.language,
            archived: a.archived,
            licenseSpdx: a.licenseSpdx,
            compatibilityStatus: a.compatibilityStatus,
            integrationPattern: a.integrationPattern,
            assetCategory: a.assetCategory,
            isPinned: Boolean(a.headSha),
            metadataJson: JSON.stringify({
              summary: a.summary,
              hardwareRequirement: a.hardwareRequirement ?? null,
              adapterId: a.adapterId ?? null,
              sbomPackages: a.sbomPackages,
            }),
          },
        })
      : await db.externalAsset.create({
          data: {
            id: randomUUID(),
            sourceId,
            fullName: a.fullName,
            url: a.url,
            kind: a.kind,
            defaultBranch: a.defaultBranch,
            headSha: a.headSha,
            stars: a.stars,
            language: a.language,
            archived: a.archived,
            licenseSpdx: a.licenseSpdx,
            compatibilityStatus: a.compatibilityStatus,
            integrationPattern: a.integrationPattern,
            assetCategory: a.assetCategory,
            isPinned: Boolean(a.headSha),
            isActive: a.compatibilityStatus !== 'incompatible',
            metadataJson: JSON.stringify({
              summary: a.summary,
              hardwareRequirement: a.hardwareRequirement ?? null,
              adapterId: a.adapterId ?? null,
              sbomPackages: a.sbomPackages,
            }),
          },
        });
    assetsUpserted += 1;

    const existingLicense = await db.licenseRecord.findFirst({ where: { assetId: assetRow.id } });
    const licenseVerdict =
      a.boundaryRequired === 'prohibited'
        ? 'prohibited'
        : a.boundaryRequired === 'legal_review_required'
          ? 'restricted'
          : a.boundaryRequired === 'external_service_only'
            ? 'conditional'
            : 'approved';
    if (!existingLicense) {
      await db.licenseRecord.create({
        data: {
          id: randomUUID(),
          assetId: assetRow.id,
          spdxId: a.licenseSpdx,
          licenseFile: a.licenseFile,
          verifiedBy: 'github-api-license-check',
          copyleftScope: a.copyleftScope,
          commercialAllowed: a.commercialAllowed,
          redistributionAllowed: a.redistributionAllowed,
          boundaryRequired: a.boundaryRequired,
          verdict: licenseVerdict,
          summary: a.summary,
        },
      });
    }

    const existingReview = await db.securityReview.findFirst({ where: { assetId: assetRow.id } });
    if (!existingReview) {
      await db.securityReview.create({
        data: {
          id: randomUUID(),
          assetId: assetRow.id,
          riskLevel: a.riskLevel,
          ssrfChecked: true,
          credentialEncryption: true,
          sandboxRequired: a.sandboxRequired,
          status: a.compatibilityStatus === 'incompatible' ? 'rejected' : a.compatibilityStatus === 'restricted' ? 'conditional' : 'approved',
          findingsJson: JSON.stringify(a.findings),
        },
      });
    }

    const existingIntegration = await db.integration.findUnique({ where: { slug: a.slug } });
    // Discovery indexes and commercial/non-integrable reference entries are persisted
    // in ExternalSource/ExternalAsset/LicenseRecord/SecurityReview, while runnable
    // Integration rows represent concrete integrations/platforms/sidecars only.
    const isIntegrableRecord =
      a.assetCategory !== 'discovery-index' &&
      a.integrationPattern !== 'EXCLUDED' &&
      a.compatibilityStatus !== 'reference_only';
    if (!existingIntegration && isIntegrableRecord) {
      const versionId = randomUUID();
      const integrationId = randomUUID();
      const pinnedRef = a.headSha ?? a.defaultBranch;
      const sbomJson = JSON.stringify({
        asset: a.fullName,
        licenseSpdx: a.licenseSpdx,
        packages: a.sbomPackages,
        checkedAt: INTAKE_FETCHED_AT,
      });
      await db.integration.create({
        data: {
          id: integrationId,
          slug: a.slug,
          name: a.fullName,
          category: a.assetCategory,
          assetId: assetRow.id,
          strategy: a.integrationPattern,
          licenseClass: a.copyleftScope,
          status:
            a.compatibilityStatus === 'integrated'
              ? 'configured'
              : a.compatibilityStatus === 'restricted' || a.compatibilityStatus === 'incompatible'
                ? 'restricted'
                : 'disabled',
          activeVersionId: versionId,
          isPinned: true,
          configJson: JSON.stringify({
            adapterId: a.adapterId ?? null,
            boundaryRequired: a.boundaryRequired,
            hardwareRequirement: a.hardwareRequirement ?? null,
          }),
        },
      });
      await db.integrationVersion.create({
        data: {
          id: versionId,
          integrationId,
          version: '1.0.0',
          pinnedRef,
          sha256: computeHash({ slug: a.slug, pinnedRef, license: a.licenseSpdx }),
          sbomJson,
          changelog: `Initial verified intake snapshot (${INTAKE_FETCHED_AT})`,
          isActive: true,
          createdBy,
        },
      });
      integrationsEnsured += 1;
    }
  }

  return { sourcesUpserted, assetsUpserted, integrationsEnsured };
}

export async function pinNewIntegrationVersion(params: {
  integrationId: string;
  version: string;
  pinnedRef: string;
  changelog: string;
  actorUserId: string;
  packages?: string[];
}) {
  const integration = await db.integration.findUnique({
    where: { id: params.integrationId },
    include: { versions: { orderBy: { createdAt: 'desc' } } },
  });
  if (!integration) {
    throw new Error('Integration not found');
  }
  const newId = randomUUID();
  const prevActive = integration.versions.find((v) => v.isActive);
  await db.$transaction([
    db.integrationVersion.updateMany({
      where: { integrationId: integration.id, isActive: true },
      data: { isActive: false },
    }),
    db.integrationVersion.create({
      data: {
        id: newId,
        integrationId: integration.id,
        version: params.version,
        pinnedRef: params.pinnedRef,
        sha256: computeHash({ id: integration.id, version: params.version, ref: params.pinnedRef }),
        sbomJson: JSON.stringify({
          packages: params.packages ?? [],
          pinnedAt: new Date().toISOString(),
        }),
        changelog: params.changelog,
        rollbackFromId: prevActive?.id ?? null,
        isActive: true,
        createdBy: params.actorUserId,
      },
    }),
    db.integration.update({
      where: { id: integration.id },
      data: { activeVersionId: newId, isPinned: true },
    }),
  ]);
  return db.integration.findUnique({
    where: { id: integration.id },
    include: { versions: { orderBy: { createdAt: 'desc' } } },
  });
}

export async function rollbackIntegrationVersion(params: {
  integrationId: string;
  targetVersionId: string;
  actorUserId: string;
}) {
  const target = await db.integrationVersion.findFirst({
    where: { id: params.targetVersionId, integrationId: params.integrationId },
  });
  if (!target) {
    throw new Error('Target version not found for integration');
  }
  await db.$transaction([
    db.integrationVersion.updateMany({
      where: { integrationId: params.integrationId, isActive: true },
      data: { isActive: false },
    }),
    db.integrationVersion.update({
      where: { id: target.id },
      data: { isActive: true },
    }),
    db.integration.update({
      where: { id: params.integrationId },
      data: { activeVersionId: target.id, isPinned: true },
    }),
  ]);
  await db.auditEvent.create({
    data: {
      id: randomUUID(),
      actorUserId: params.actorUserId,
      action: 'asset_vault.rollback',
      resource: 'Integration',
      resourceId: params.integrationId,
      details: JSON.stringify({ targetVersionId: target.id, version: target.version }),
    },
  }).catch(() => undefined);

  return db.integration.findUnique({
    where: { id: params.integrationId },
    include: { versions: { orderBy: { createdAt: 'desc' } } },
  });
}

